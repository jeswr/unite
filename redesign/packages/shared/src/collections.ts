/** Each collection's schema: the store validates every write against it. */
export const COLLECTION_SCHEMAS = {
  persons: PersonSchema,
  memberships: MembershipSchema,
  invites: InviteSchema,
  assemblies: AssemblySchema,
  conversations: ConversationSchema,
  turns: TurnSchema,
  points: PointSchema,
  themes: ThemeSchema,
  reports: ReportSchema,
  statements: StatementSchema,
  reactions: ReactionSchema,
  reasons: ReasonSchema,
  objections: ObjectionSchema,
  evidenceCards: EvidenceCardSchema,
  rooms: RoomSchema,
  roomMessages: RoomMessageSchema,
  roomAnswers: RoomAnswerSchema,
  priorityChoices: PriorityChoiceSchema,
  decisions: DecisionSchema,
  buildProposals: BuildProposalSchema,
  deliveryItems: DeliveryItemSchema,
  checks: CheckSchema,
  feedback: FeedbackSchema,
  spend: SpendSchema,
  intakes: IntakeSchema,
} as const satisfies Record<keyof typeof COLLECTIONS, z.ZodType>;

export type CollectionName = keyof typeof COLLECTIONS;
export const COLLECTION_NAMES = Object.keys(COLLECTIONS) as CollectionName[];

/** The record type stored in a collection. */
export type DocOf<C extends CollectionName> = z.infer<(typeof COLLECTION_SCHEMAS)[C]>;

